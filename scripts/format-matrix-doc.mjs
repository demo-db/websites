// Renders docs/format-matrix.md from config/format-matrix.json (the declaration), the generated registry
// index (what the build produced) and config/derived-exports.lock.json. The document contains nothing that
// depends on the zlib build that encoded a file, so it is identical on every machine; the test suite
// compares it with the committed file, and `node scripts/format-matrix-doc.mjs --write` regenerates it.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { EXTRA_FORMATS } from './format-matrix.mjs';

const MIB = 1024 * 1024;
const originText = { provider: 'provider file', 'provider-artifact': 'provider artifact', derived: 'generated here', archive: 'archive of the pinned inGitDB edition' };
const mib = (bytes) => `${(bytes / MIB).toFixed(bytes >= 10 * MIB ? 0 : 1)} MiB`;

function sizeCell(db, format, lock) {
  const item = db.exports.find((candidate) => candidate.format === format && !candidate.table);
  if (!item) return 'none';
  if (format === 'ingitdb') {
    const pinned = lock.datasets?.[db.id]?.ingitdb;
    return `ZIP, ${pinned.fileCount} files, ${pinned.rowCount.toLocaleString('en-US')} rows`;
  }
  const decoded = item.decodedBytes ?? item.bytes;
  return `${mib(decoded)}${item.compression === 'gzip' ? ' (served gzip-encoded)' : ''}`;
}

export function renderMatrixDoc({ matrix, databases, lock }) {
  const formats = matrix.formats;
  const labels = matrix.labels;
  const ids = Object.keys(matrix.datasets);
  const name = (id) => databases.find((db) => db.id === id)?.name ?? id;
  const lines = [];
  const emit = (...rows) => lines.push(...rows);
  emit('# Format coverage and validation matrix', '',
    '<!-- Generated by `node scripts/format-matrix-doc.mjs --write` from config/format-matrix.json, the built registry index and',
    'config/derived-exports.lock.json. Do not edit by hand: scripts/test-format-matrix.mjs fails when this file is stale. -->', '',
    'Which complete-database format each registered dataset offers as a download, where it comes from, how it is checked, and, for every format',
    'that is not offered, why not. The declaration is `config/format-matrix.json`. The build refuses to finish unless the exports it produced are exactly',
    'the declared ones, the declaration is published in each dataset\'s metadata (`formatAvailability` in `corpus.json` and the page data), and the',
    'dataset and download pages print "Not available: <reason>" for every gap.', '');

  emit('## Final matrix', '', `| Dataset | ${formats.map((format) => labels[format]).join(' | ')} |`, `|---|${formats.map(() => '---').join('|')}|`);
  for (const id of ids) {
    const cells = formats.map((format) => {
      const cell = matrix.datasets[id][format];
      return cell.state === 'download' ? `yes (${originText[cell.origin]})` : 'not available';
    });
    emit(`| ${name(id)} | ${cells.join(' | ')} |`);
  }
  emit('', 'Every dataset also offers the SQLite-dialect SQL dump (`sql`, labelled "SQL (SQLite dialect)": it is SQLite syntax, not PostgreSQL, MySQL or SQL Server),',
    'per-table JSON and CSV files, the schema, model and meaning files, and a research snapshot ZIP. Those are outside the matrix.', '');

  emit('## Initial and final state', '',
    `Initial is origin/main at \`${matrix.baseline.commit}\`, read from the live corpus on ${matrix.baseline.verifiedLive}; final is this build.`, '',
    `| Dataset | ${formats.map((format) => labels[format]).join(' | ')} |`, `|---|${formats.map(() => '---').join('|')}|`);
  for (const id of ids) {
    const cells = formats.map((format) => {
      const cell = matrix.datasets[id][format];
      return `${matrix.baseline.datasets[id][format]} → ${cell.state === 'download' ? 'served' : 'not available'}`;
    });
    emit(`| ${name(id)} | ${cells.join(' | ')} |`);
  }
  emit('');

  emit('## Not available, and why', '');
  for (const id of ids) {
    for (const format of formats) {
      const cell = matrix.datasets[id][format];
      if (cell.state !== 'unavailable') continue;
      emit(`- **${name(id)}, ${labels[format]}.** ${cell.reason}${cell.followUp ? ` Follow-up: ${cell.followUp}` : ''}`);
    }
  }
  emit('');

  emit('## Size and hosting', '',
    `Static assets are limited to ${mib(25 * MIB)} per file. A file above that is stored gzip-encoded at level 9 and served decoded by the Worker; if the`,
    'encoded stream is still above the limit it is split in `.part` files that the Worker joins (the provider SQLite for AdventureWorks is served that way).',
    'No download in this matrix is partial. Sizes are decoded sizes.', '',
    `| Dataset | ${formats.filter((format) => format !== 'mysql' && format !== 'sqlserver').map((format) => labels[format]).join(' | ')} |`,
    `|---|${formats.filter((format) => format !== 'mysql' && format !== 'sqlserver').map(() => '---').join('|')}|`);
  for (const id of ids) {
    const db = databases.find((candidate) => candidate.id === id);
    emit(`| ${name(id)} | ${formats.filter((format) => format !== 'mysql' && format !== 'sqlserver').map((format) => sizeCell(db, format, lock)).join(' | ')} |`);
  }
  emit('', 'The AdventureWorks inGitDB archive is the one download close to the limit; the build fails, rather than publish a partial file, if it ever exceeds it.', '');

  emit('## How each format is produced', '',
    '- **SQLite, per-table JSON and CSV, the SQLite-dialect SQL dump**: provider contract files, verified against the provider checksums pinned in `config/databases.json`.',
    '- **JSON** (generated): `scripts/derived-exports.mjs` joins the provider\'s per-table JSON arrays, unparsed, as `{"<table>": [rows]}`, so values (exact decimals, base64 BLOBs) are the provider bytes.',
    '- **YAML** (generated): the same rows as block-style YAML. Every scalar is a JSON scalar and numbers are written exactly as in the source JSON.',
    '- **PostgreSQL script**: `scripts/hosting-tools/postgres_samples.py generate` over the pinned SQLite fixture (guarded schema named after the dataset, deferred foreign keys, one transaction).',
    '  Northwind uses its provider\'s own pinned `artifacts/hosting-imports/postgres.sql`, and Chinook its upstream Chinook_PostgreSql.sql, both provider-checksummed.',
    '- **inGitDB archive**: `scripts/hosting-tools/ingitdb_archive.py` packs the provider\'s `ingitdb/` directory at the revision pinned in `ingitdbRevisions`, unchanged, after checking its',
    '  export manifest names the same dataset and the same SQLite fixture SHA-256 and records a clean parity check. The inGitDB directory itself is written by DataTug\'s DALgo to inGitDB export in the provider repository.',
    '- **MySQL and SQL Server scripts**: Chinook\'s are the unchanged upstream scripts; for the other datasets see the reasons above.', '',
    'Every generated file is pinned by `config/derived-exports.lock.json` (decoded SHA-256 and size; for the inGitDB archive the digest of its file list), so a change to a generator, an input or an interpreter',
    'that alters a published byte fails the build until the lock is regenerated (`DEMODB_UPDATE_DERIVED_LOCK=1 node scripts/prepare-databases.mjs`, refused in CI) and the diff is reviewed.', '');

  emit('## Validation', '',
    'In every pull request (`pnpm test`, `scripts/test-format-matrix.mjs`, against the built site):',
    '',
    '- the declaration, the registry index, `corpus.json`, the rendered pages and the files in the built asset tree describe the same set of downloads, and a served file is within the size limit;',
    '- the complete JSON and YAML of every dataset that has them: table set and order, row counts equal to the schema and to `SELECT count(*)` on the pinned SQLite fixture, every row and value equal to the fixture (BLOBs as base64),',
    '  primary keys unique, every foreign-key value present in the referenced column, and the YAML equal to the JSON (parsed with the `yaml` package for datasets up to 12 MB, and a sample of tables above that);',
    '- this document is current.', '',
    'In `.github/workflows/served-formats.yml`, against the built asset tree and the provider checkouts at the pinned revisions:',
    '',
    '- every served PostgreSQL script is loaded into a throwaway PostgreSQL 17 and compared with the fixture: same tables, row counts, primary-key columns and foreign-key counts, plus the full typed row-multiset check for scripts the shared generator wrote (`validate_served_formats.py`);',
    '- every inGitDB archive is extracted and compared row by row and definition by definition with the fixture by the independent parity checker (`validate_datatug_exports.py`).', '',
    'After deploy, `scripts/smoke-live.mjs` downloads every complete export listed in `corpus.json` and compares size and SHA-256.', '');

  emit('## What remains', '',
    '- MySQL and SQL Server scripts for Northwind, Pubs, Sakila, AdventureWorks and Employees: needs a dialect in the shared generator and a MySQL and a SQL Server service in CI to verify it (see the follow-ups above).',
    '- The inGitDB archives are validated by the independent parity checker; validating them with the inGitDB CLI in CI needs a CLI release that reads the DataTug 0.61.1 collection definitions (v0.70.0 or newer).',
    `- Formats outside the matrix: ${EXTRA_FORMATS.join(', ')} are listed in the registry but are not matrix formats.`, '');
  return `${lines.join('\n').trimEnd()}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const matrix = JSON.parse(await readFile(join(root, 'config/format-matrix.json'), 'utf8'));
  const lock = JSON.parse(await readFile(join(root, 'config/derived-exports.lock.json'), 'utf8'));
  const { databases } = JSON.parse(await readFile(join(root, 'src/data/generated/index.json'), 'utf8'));
  const text = renderMatrixDoc({ matrix, databases, lock });
  const target = join(root, 'docs/format-matrix.md');
  if (process.argv.includes('--write')) { await writeFile(target, text); console.log(`Wrote ${target}`); }
  else process.stdout.write(text);
}
